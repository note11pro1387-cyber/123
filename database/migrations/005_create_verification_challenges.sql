CREATE TABLE verification_challenges (
    id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    purpose ENUM('registration','password_reset') NOT NULL,
    subject_type ENUM('registration_attempt','user') NOT NULL,
    registration_attempt_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    user_id BIGINT UNSIGNED NULL,
    user_channel_id BIGINT UNSIGNED NULL,
    channel_type ENUM('email','telegram') NOT NULL,
    destination_value VARCHAR(255) NOT NULL,
    destination_normalized VARCHAR(255) NOT NULL,
    code_hmac CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state ENUM('active','verified_reset','used','revoked','exhausted') NOT NULL DEFAULT 'active',
    attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts TINYINT UNSIGNED NOT NULL DEFAULT 5,
    resend_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
    last_sent_at DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    used_at DATETIME(6) NULL,
    recovery_token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    recovery_expires_at DATETIME(6) NULL,
    recovery_used_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY ix_challenges_active_subject (purpose, subject_type, user_id, registration_attempt_id, state, expires_at),
    UNIQUE KEY uq_challenges_recovery_token_hash (recovery_token_hash),
    KEY ix_challenges_destination (channel_type, destination_normalized, purpose, created_at),
    CONSTRAINT fk_challenges_registration_attempt FOREIGN KEY (registration_attempt_id) REFERENCES registration_attempts(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_challenges_user FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_challenges_user_channel_owner FOREIGN KEY (user_channel_id, user_id, channel_type) REFERENCES user_channels(id, user_id, channel_type) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_challenge_subject_binding CHECK ((subject_type = 'registration_attempt' AND purpose = 'registration' AND registration_attempt_id IS NOT NULL AND user_id IS NULL AND user_channel_id IS NULL) OR (subject_type = 'user' AND purpose = 'password_reset' AND user_id IS NOT NULL AND registration_attempt_id IS NULL AND user_channel_id IS NOT NULL)),
    CONSTRAINT chk_challenge_recovery_state CHECK (state <> 'verified_reset' OR (purpose = 'password_reset' AND used_at IS NOT NULL AND recovery_token_hash IS NOT NULL AND recovery_expires_at IS NOT NULL AND recovery_used_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
