CREATE TABLE registration_attempts (
    id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    username VARCHAR(32) NOT NULL,
    username_normalized VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phone VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phone_normalized VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    email_value VARCHAR(255) NULL,
    email_normalized VARCHAR(255) NULL,
    password_hash VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    selected_channel ENUM('telegram','email') NOT NULL,
    telegram_link_nonce_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    linked_telegram_user_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    linked_telegram_chat_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    telegram_linked_at DATETIME(6) NULL,
    terms_version VARCHAR(64) NULL,
    terms_accepted_at DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    consumed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_user_id BIGINT UNSIGNED NULL,
    PRIMARY KEY (id),
    KEY ix_registration_attempts_expiry (consumed_at, expires_at),
    KEY ix_registration_attempts_username (username_normalized),
    KEY ix_registration_attempts_phone (phone_normalized),
    CONSTRAINT fk_registration_attempts_created_user FOREIGN KEY (created_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_registration_attempts_channel CHECK (selected_channel <> 'email' OR email_normalized IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
