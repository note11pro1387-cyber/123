CREATE TABLE projects (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    tracking_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_user_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(180) NOT NULL,
    project_type VARCHAR(64) NOT NULL,
    status ENUM('submitted','under_review','needs_information','in_progress','waiting_for_client','completed','rejected','cancelled') NOT NULL DEFAULT 'submitted',
    progress TINYINT UNSIGNED NOT NULL DEFAULT 0,
    brief_json LONGTEXT NOT NULL,
    submitted_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    cancelled_at DATETIME(6) NULL,
    cancelled_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    cancel_reason VARCHAR(500) NULL,
    rejection_reason VARCHAR(500) NULL,
    archived_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_projects_public_id (public_id),
    UNIQUE KEY uq_projects_tracking_code (tracking_code),
    KEY ix_projects_owner_created (owner_user_id, created_at),
    KEY ix_projects_status_created (status, created_at),
    KEY ix_projects_owner_status (owner_user_id, status),
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_projects_progress CHECK (progress <= 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
