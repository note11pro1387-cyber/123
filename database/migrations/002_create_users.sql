CREATE TABLE users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    legacy_id VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    legacy_source_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    full_name VARCHAR(160) NOT NULL,
    username VARCHAR(32) NOT NULL,
    username_normalized VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phone VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phone_normalized VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    password_hash VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    legacy_verified TINYINT(1) NOT NULL DEFAULT 0,
    legacy_telegram_username VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    legacy_extra_json LONGTEXT NULL,
    account_status ENUM('active','suspended','pending','closed') NOT NULL DEFAULT 'pending',
    terms_version VARCHAR(64) NULL,
    terms_accepted_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    last_login_at DATETIME(6) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_public_id (public_id),
    UNIQUE KEY uq_users_legacy_id (legacy_id),
    UNIQUE KEY uq_users_username_normalized (username_normalized),
    UNIQUE KEY uq_users_phone_normalized (phone_normalized),
    KEY ix_users_status_created (account_status, created_at),
    KEY ix_users_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
